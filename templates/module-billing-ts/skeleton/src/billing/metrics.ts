import { metrics } from "@opentelemetry/api";

// ── Billing Metrics ───────────────────────────────────────────────
//
// OTel counters for billing observability. Tracks usage recording,
// invoice generation, charge calls, and the amounts charges collected.
// No-ops unless an OTel SDK is wired in by the consumer.
//

const meter = metrics.getMeter("__PROJECT_NAME__");

/** Total usage events recorded, labeled by metric name. */
export const billingUsageRecorded = meter.createCounter("billing_usage_recorded", {
  description: "Total usage events recorded by metric name",
});

/** Total invoices generated, labeled by status. */
export const billingInvoiceGenerated = meter.createCounter("billing_invoice_generated", {
  description: "Total invoices generated by status",
});

/**
 * Amounts charge calls collected, in the smallest unit of the invoice's
 * currency, labeled by `currency` (lowercase ISO 4217). A call adds what its
 * own payment request collected: nothing when an earlier charge of the
 * invoice had paid it, or when the provider answered it from an earlier
 * request's stored payment. Each payment therefore counts at most once.
 */
export const billingPaymentTotal = meter.createCounter("billing_payment_total", {
  description: "Amount charge calls collected, in the smallest unit of the currency attribute",
  unit: "{minor_unit}",
});

/**
 * Charge calls, labeled by `result`: `paid`, or the failure code of a call
 * that did not leave its invoice paid. Every call counts once, so a charge
 * retried after `unavailable` counts once per attempt.
 */
export const billingChargeCalls = meter.createCounter("billing_charge_calls", {
  description: "Charge calls by result: paid, or the failure code",
  unit: "{call}",
});
